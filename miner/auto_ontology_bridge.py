    @classmethod
    def build_terms_payload(cls, terms_definitions: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """
        Builds payload for Auto-Ontology /api/terms endpoint with synonym mapping.
        """
        payload = []
        for t in terms_definitions:
            payload.append({
                "id": t.get("id"),
                "name": t.get("name"),
                "description": t.get("description"),
                "source": "semantic",
                "synonyms": t.get("synonyms", []),
                "name_certified": True,
                "description_certified": True
            })
        return payload

    @classmethod
    def transform_incidents_to_relational_rows(
        cls, 
        incidents: List[Dict[str, Any]]
    ) -> Dict[str, List[Dict[str, Any]]]:
        """
        Normalizes unstructured/distilled incident entities into 3NF tabular rows
        covering products, process routes, steps, recipes, equipment, layers, and facts.
        """
        products: Dict[str, Dict[str, Any]] = {}
        routes: Dict[str, Dict[str, Any]] = {}
        steps: Dict[str, Dict[str, Any]] = {}
        recipes: Dict[str, Dict[str, Any]] = {}
        equipments: Dict[str, Dict[str, Any]] = {}
        layers: Dict[str, Dict[str, Any]] = {}
        defects: Dict[str, Dict[str, Any]] = {}
        fact_incidents: List[Dict[str, Any]] = []
        fact_actions: List[Dict[str, Any]] = []

        incident_seq = 1
        action_seq = 1

        for inc in incidents:
            # 1. Product Model
            prod_id = inc.get("product_id") or "PROD_GENERIC"
            if prod_id not in products:
                products[prod_id] = {
                    "product_id": prod_id,
                    "product_name": inc.get("product_name", "Standard Display Module"),
                    "resolution": inc.get("resolution", "1080x1920"),
                    "display_size_inch": inc.get("display_size_inch", 5.5),
                    "ppi": inc.get("ppi", 401.0),
                    "display_tech": inc.get("display_tech", "LTPS-LCD"),
                    "fab_generation": inc.get("fab_generation", "Fab-G6")
                }

            # 2. Process Route
            route_id = inc.get("route_id") or f"ROUTE_{prod_id}"
            if route_id not in routes:
                routes[route_id] = {
                    "route_id": route_id,
                    "route_name": inc.get("route_name", f"{prod_id} Standard Route"),
                    "mask_count": inc.get("mask_count", 9),
                    "product_id": prod_id,
                    "is_active": True
                }

            # 3. Process Layer
            layer_id = inc.get("layer_id") or "LAYER_GENERAL"
            if layer_id not in layers:
                layers[layer_id] = {
                    "layer_id": layer_id,
                    "layer_name": inc.get("layer_name", layer_id),
                    "material_type": inc.get("material_type", "Photoresist"),
                    "thickness_spec_nm": inc.get("thickness_spec_nm", 1000.0),
                    "is_thick_film": inc.get("is_thick_film", False)
                }

            # 4. Route Step
            step_id = inc.get("step_id") or f"STEP_{layer_id}"
            if step_id not in steps:
                steps[step_id] = {
                    "step_id": step_id,
                    "route_id": route_id,
                    "step_seq": inc.get("step_seq", 100),
                    "step_name": inc.get("step_name", f"Lithography_{layer_id}"),
                    "layer_id": layer_id,
                    "station_type": inc.get("station_type", "PHOTO")
                }

            # 5. Equipment
            eq_id = inc.get("equipment_id") or "EQ_UNKNOWN"
            if eq_id not in equipments:
                equipments[eq_id] = {
                    "equipment_id": eq_id,
                    "equipment_name": inc.get("equipment_name", eq_id),
                    "equipment_group": inc.get("equipment_group", "Track"),
                    "sub_unit": inc.get("sub_unit", "Main"),
                    "vendor": inc.get("vendor", "OEM"),
                    "fab_line": inc.get("fab_line", "Fab-G6")
                }

            # 6. Recipe
            recipe_id = inc.get("recipe_id") or f"REC_{eq_id}_{layer_id}"
            if recipe_id not in recipes:
                recipes[recipe_id] = {
                    "recipe_id": recipe_id,
                    "recipe_name": inc.get("recipe_name", f"Standard_{recipe_id}"),
                    "equipment_id": eq_id,
                    "step_id": step_id,
                    "dose_mj": inc.get("dose_mj", 35.0),
                    "focus_offset_um": inc.get("focus_offset_um", 0.0),
                    "temperature_c": inc.get("temperature_c", 110.0),
                    "flow_rate_lmin": inc.get("flow_rate_lmin", 200.0),
                    "scan_speed_mms": inc.get("scan_speed_mms", 120.0),
                    "recipe_version": inc.get("recipe_version", "v1.0")
                }

            # 7. Defect Type
            defect_code = inc.get("defect_code") or "DEF_UNKNOWN"
            if defect_code not in defects:
                defects[defect_code] = {
                    "defect_code": defect_code,
                    "defect_name_zh": inc.get("defect_name_zh", defect_code),
                    "defect_category": inc.get("defect_category", "Mura"),
                    "manifest_station": inc.get("manifest_station", "MAC_ANN")
                }

            # 8. Fact Defect Incident
            current_inc_id = incident_seq
            incident_seq += 1

            fact_incidents.append({
                "incident_id": current_inc_id,
                "lot_id": inc.get("lot_id", f"LOT_{current_inc_id:04d}"),
                "occurred_date": inc.get("occurred_date", "2026-01-01"),
                "product_id": prod_id,
                "step_id": step_id,
                "recipe_id": recipe_id,
                "equipment_id": eq_id,
                "layer_id": layer_id,
                "defect_code": defect_code,
                "impact_yield_loss_pct": inc.get("impact_yield_loss_pct", 0.0),
                "scrap_sheet_count": inc.get("scrap_sheet_count", 0),
                "detect_station": inc.get("detect_station", "MAC"),
                "source_evidence_title": inc.get("source_evidence_title", "Engineering memo")
            })

            # 9. Fact Root Cause Action
            action = inc.get("root_cause_action")
            if action:
                fact_actions.append({
                    "action_id": action_seq,
                    "incident_id": current_inc_id,
                    "root_cause_physical": action.get("root_cause_physical", "Empirical trigger"),
                    "target_unit": action.get("target_unit", "Machine"),
                    "param_name": action.get("param_name", "parameter"),
                    "param_unit": action.get("param_unit", ""),
                    "param_before": action.get("param_before", "N/A"),
                    "param_after": action.get("param_after", "N/A"),
                    "countermeasure_summary": action.get("countermeasure_summary", "Standardized"),
                    "verification_status": action.get("verification_status", "Verified"),
                    "report_doc_name": action.get("report_doc_name", "investigation_report.ppt")
                })
                action_seq += 1

        return {
            "dim_product_model": list(products.values()),
            "dim_process_route": list(routes.values()),
            "dim_process_layer": list(layers.values()),
            "dim_route_step": list(steps.values()),
            "dim_equipment": list(equipments.values()),
            "dim_recipe": list(recipes.values()),
            "dim_defect_type": list(defects.values()),
            "fact_defect_incident": fact_incidents,
            "fact_root_cause_action": fact_actions
        }

