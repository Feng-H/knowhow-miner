"""
NVIDIA Auto-Ontology Bridge Module
SPDX-License-Identifier: CC-BY-NC-SA-4.0

Transforms mined industrial manufacturing causal quintets and decision state machines
into normalized relational database schemas (3NF) and official model interchange documents
strictly aligned with NVIDIA Auto-Ontology (NVIDIA/auto-ontology, Apache-2.0).

Aligned with NVIDIA Auto-Ontology specs:
  1. Relational 3NF Schema (dim_equipment, dim_process_layer, dim_defect_type,
     fact_defect_incident, fact_root_cause_action)
  2. Model Interchange Document (data_layer + semantic_layer YAML conforming to
     auto_ontology.server.model_interchange.schemas.AutoOntologyModelDocument)
  3. Model-Interchange Import API (/api/model/import with multipart YAML)
  4. Standard Model Context Protocol (MCP) tool integration specs (check_readiness,
     check_answerable, search_terms, get_term, get_term_columns, get_sql_attribute, ask_question)
"""

from typing import Dict, Any, List, Optional
