    @classmethod
    def export_auto_ontology_yaml(cls, database_name: str = "manufacturing_kb") -> str:
        """
        Exports the complete AutoOntologyModelDocument as valid YAML for POST /api/model/import.
        Uses PyYAML if installed; falls back to an indented YAML serializer for standard library.
        """
        doc = cls.generate_model_interchange_document(database_name=database_name)
        if HAS_YAML:
            import yaml  # type: ignore
            return yaml.dump(doc, allow_unicode=True, sort_keys=False)
        
        # Pure-Python YAML dumper fallback (handles dictionaries, lists, strings, booleans, numbers)
        def _to_yaml(data: Any, indent_level: int = 0) -> str:
            sp = "  " * indent_level
            if isinstance(data, dict):
                lines = []
                for k, v in data.items():
                    if isinstance(v, (dict, list)):
                        lines.append(f"{sp}{k}:")
                        lines.append(_to_yaml(v, indent_level + 1))
                    else:
                        if isinstance(v, bool):
                            val_str = "true" if v else "false"
                        elif v is None:
                            val_str = "null"
                        elif isinstance(v, str) and ("\n" in v or ":" in v or "#" in v):
                            # Multiline or special characters
                            val_str = f"|\n{sp}  " + v.replace("\n", f"\n{sp}  ")
                        else:
                            val_str = str(v)
                        lines.append(f"{sp}{k}: {val_str}")
                return "\n".join(lines)
            elif isinstance(data, list):
                lines = []
                for item in data:
                    if isinstance(item, dict):
                        # First key gets the - prefix
                        keys = list(item.keys())
                        if not keys:
                            lines.append(f"{sp}- {{}}")
                            continue
                        first_k = keys[0]
                        first_v = item[first_k]
                        if isinstance(first_v, (dict, list)):
                            lines.append(f"{sp}- {first_k}:")
                            lines.append(_to_yaml(first_v, indent_level + 2))
                        else:
                            v_str = ("true" if first_v else "false") if isinstance(first_v, bool) else (str(first_v) if first_v is not None else "null")
                            lines.append(f"{sp}- {first_k}: {v_str}")
                        for rem_k in keys[1:]:
                            rem_v = item[rem_k]
                            if isinstance(rem_v, (dict, list)):
                                lines.append(f"{sp}  {rem_k}:")
                                lines.append(_to_yaml(rem_v, indent_level + 2))
                            else:
                                rem_str = ("true" if rem_v else "false") if isinstance(rem_v, bool) else (str(rem_v) if rem_v is not None else "null")
                                lines.append(f"{sp}  {rem_k}: {rem_str}")
                    else:
                        lines.append(f"{sp}- {item}")
                return "\n".join(lines)
            return f"{sp}{data}"

        return _to_yaml(doc)

