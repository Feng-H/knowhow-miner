    @classmethod
    def export_auto_ontology_yaml(cls, database_name: str = "manufacturing_kb") -> str:
        """
        Exports the complete AutoOntologyModelDocument as valid YAML for POST /api/model/import.
        Uses PyYAML if installed; falls back to an indented YAML serializer for standard library.
        """
        doc = cls.generate_model_interchange_document(database_name=database_name)
        if HAS_YAML:
            import yaml  # type: ignore
            return yaml.dump(doc, allow_unicode=True, sort_keys=False)
        
        # Pure-Python YAML dumper fallback
        def _format_val(val: Any, indent_level: int) -> str:
            if isinstance(val, bool):
                return "true" if val else "false"
            if val is None:
                return "null"
            if isinstance(val, (int, float)):
                return str(val)
            s = str(val)
            if "\n" in s:
                sp = "  " * (indent_level + 1)
                lines = [f"{sp}{line}" for line in s.splitlines()]
                return "|\n" + "\n".join(lines)
            if any(c in s for c in [": ", "#", "{", "}", "[", "]", ",", "&", "*", "?", "|", "-", "<", ">", "=", "!", "%", "@", "`", '"', "'"]) or s.startswith(("-", "?", ":")):
                return json.dumps(s, ensure_ascii=False)
            return s

        def _to_yaml(data: Any, indent_level: int = 0) -> str:
            sp = "  " * indent_level
            if isinstance(data, dict):
                lines = []
                for k, v in data.items():
                    if isinstance(v, list) and not v:
                        lines.append(f"{sp}{k}: []")
                    elif isinstance(v, dict) and not v:
                        lines.append(f"{sp}{k}: {{}}")
                    elif isinstance(v, (dict, list)):
                        lines.append(f"{sp}{k}:")
                        lines.append(_to_yaml(v, indent_level + 1))
                    else:
                        formatted = _format_val(v, indent_level)
                        if formatted.startswith("|\n"):
                            lines.append(f"{sp}{k}: {formatted}")
                        else:
                            lines.append(f"{sp}{k}: {formatted}")
                return "\n".join(lines)
            elif isinstance(data, list):
                lines = []
                for item in data:
                    if isinstance(item, dict):
                        keys = list(item.keys())
                        if not keys:
                            lines.append(f"{sp}- {{}}")
                            continue
                        first_k = keys[0]
                        first_v = item[first_k]
                        if isinstance(first_v, (dict, list)):
                            lines.append(f"{sp}- {first_k}:")
                            lines.append(_to_yaml(first_v, indent_level + 2))
                        else:
                            formatted = _format_val(first_v, indent_level + 1)
                            lines.append(f"{sp}- {first_k}: {formatted}")
                        for rem_k in keys[1:]:
                            rem_v = item[rem_k]
                            if isinstance(rem_v, (dict, list)):
                                lines.append(f"{sp}  {rem_k}:")
                                lines.append(_to_yaml(rem_v, indent_level + 2))
                            else:
                                formatted = _format_val(rem_v, indent_level + 1)
                                lines.append(f"{sp}  {rem_k}: {formatted}")
                    else:
                        lines.append(f"{sp}- {_format_val(item, indent_level)}")
                return "\n".join(lines)
            return f"{sp}{_format_val(data, indent_level)}"

        return _to_yaml(doc)

